import { notFound } from "next/navigation";
import { PrintButton } from "@/components/PrintButton";
import { currentSession } from "@/lib/auth";
import { allows } from "@/lib/session";
import { inr } from "@/lib/format";
import { api } from "@/lib/zyvor";

export const dynamic = "force-dynamic";

type Line = { position: number; description: string; hsn_sac: string; quantity: number; unit_price_minor: number; taxable_minor: number; rate_bp: number; cgst_minor: number; sgst_minor: number; igst_minor: number };
const addr = (...p: (string | null | undefined)[]) => p.filter(Boolean).join(", ");

// A printable invoice (browser print gives a PDF). With tax lines it is laid out as a GST tax invoice; without them
// it is a plain invoice. It is the same data as the API, so it shows only what was stored.
export default async function InvoicePrint({ params }: { params: Promise<{ id: string }> }) {
  const me = await currentSession();
  if (!me || !allows(me.r, "finance")) notFound();
  const { id } = await params;
  const z = api(me.u);
  const inv = await z.invoices.retrieve(id).catch(() => null) as null | { number: string; currency: string; amount_minor: number; tax_minor: number; status: string; due_date: string | null; issued_on: string; customer_id: string | null; place_of_supply: string | null; buyer_gstin: string | null; reverse_charge: boolean; paid_minor: number; credited_minor: number; outstanding_minor: number };
  if (!inv) notFound();
  const [settings, customer, tax] = await Promise.all([
    z.settings.get(),
    inv.customer_id ? z.customers.get(inv.customer_id).catch(() => null) : Promise.resolve(null),
    z.invoices.lines(id).catch(() => null) as Promise<null | { lines: Line[] }>,
  ]);
  const lines = tax?.lines ?? [];
  const isTax = lines.length > 0;
  const seller = settings.gst;
  const money = (m: number) => (inv.currency === "INR" ? inr(m) : `${inv.currency} ${(m / 100).toFixed(2)}`);
  return (
    <main className="invoice">
      <style>{`.invoice{max-width:820px;margin:24px auto;padding:0 20px;font:14px/1.5 system-ui,sans-serif;color:#111;background:#fff}.invoice table{width:100%;border-collapse:collapse;margin:16px 0}.invoice th,.invoice td{border-bottom:1px solid #ccc;padding:6px 8px;text-align:left}.invoice .r{text-align:right}.invoice .two{display:grid;grid-template-columns:1fr 1fr;gap:24px}.invoice h1{font-size:20px;margin:0}.invoice small{color:#555}@media print{.no-print{display:none}.invoice{margin:0}}`}</style>
      <div className="no-print" style={{ textAlign: "right" }}><PrintButton /></div>
      <h1>{isTax ? "Tax invoice" : "Invoice"} {inv.number}</h1>
      <small>Date {inv.issued_on}{inv.due_date ? ` · Due ${inv.due_date}` : ""} · {inv.status.replace("_", " ")}</small>
      <div className="two" style={{ marginTop: 16 }}>
        <div><strong>{seller.legal_name ?? "Seller"}</strong><br />{addr(seller.address1, seller.location, seller.pincode)}{seller.gstin && <><br />GSTIN {seller.gstin}</>}</div>
        <div><strong>Bill to: {customer?.name ?? "—"}</strong><br />{addr(customer?.address1, customer?.location, customer?.pincode)}{(inv.buyer_gstin ?? customer?.gstin) && <><br />GSTIN {inv.buyer_gstin ?? customer?.gstin}</>}{inv.place_of_supply && <><br />Place of supply {inv.place_of_supply}</>}</div>
      </div>
      {isTax ? (
        <div style={{ overflowX: "auto" }}><table>
          <thead><tr><th>#</th><th>Description</th><th>HSN/SAC</th><th className="r">Qty</th><th className="r">Rate</th><th className="r">Taxable</th><th className="r">Tax %</th><th className="r">CGST</th><th className="r">SGST</th><th className="r">IGST</th></tr></thead>
          <tbody>
            {lines.map((l) => (
              <tr key={l.position}><td>{l.position}</td><td>{l.description}</td><td>{l.hsn_sac}</td><td className="r">{l.quantity}</td><td className="r">{money(l.unit_price_minor)}</td><td className="r">{money(l.taxable_minor)}</td><td className="r">{(l.rate_bp / 100).toFixed(2)}</td><td className="r">{money(l.cgst_minor)}</td><td className="r">{money(l.sgst_minor)}</td><td className="r">{money(l.igst_minor)}</td></tr>
            ))}
          </tbody>
        </table></div>
      ) : (
        <table><tbody><tr><td>Amount due for invoice {inv.number}</td><td className="r">{money(inv.amount_minor)}</td></tr></tbody></table>
      )}
      <p className="r" style={{ textAlign: "right" }}>
        {isTax && <>Tax {money(inv.tax_minor)}<br /></>}
        <strong>Total {money(inv.amount_minor)}</strong>
        {inv.credited_minor > 0 && <><br />Credit notes −{money(inv.credited_minor)}</>}
        {inv.paid_minor > 0 && <><br />Paid −{money(inv.paid_minor)}</>}
        <br /><strong>Balance {money(inv.outstanding_minor)}</strong>
      </p>
      {inv.reverse_charge && <p>Tax is payable on reverse charge.</p>}
      <small>Generated by Zyvor from the stored invoice. Not an IRN-bearing e-invoice unless you registered it on the e-invoice portal.</small>
    </main>
  );
}
