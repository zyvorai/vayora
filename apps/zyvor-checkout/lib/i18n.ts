export const MESSAGES: Record<Lang, Record<Key, string>> = { en, hi, mr, ta, te, bn };

/** Look up a string and fill its {placeholders}. */
export function translate(lang: Lang, key: Key, vars: Record<string, string> = {}): string {
  return MESSAGES[lang][key].replace(/\{(\w+)\}/g, (_, k: string) => vars[k] ?? `{${k}}`);
}

/** `?lang=hi` wins, then a remembered choice, then the browser's language; otherwise English. */
export function pickLang(query: string | null, saved: string | null, browser: readonly string[]): Lang {
  const ok = (v: string | null | undefined): Lang | null => {
    const c = (v ?? "").toLowerCase().split("-")[0];
    return c in LANGS ? (c as Lang) : null;
  };
  return ok(query) ?? ok(saved) ?? browser.map(ok).find(Boolean) ?? "en";
}
