export const EVENT_MESSAGES: Partial<Record<Lang, Partial<Record<EvtKey, string>>>> = { en, hi };

/** Look up a string for the language, falling back to English, and fill its {placeholders}. */
export function evt(lang: Lang, key: EvtKey, vars: Record<string, string> = {}): string {
  const text = EVENT_MESSAGES[lang]?.[key] ?? en[key];
  return text.replace(/\{(\w+)\}/g, (_, k: string) => vars[k] ?? `{${k}}`);
}
